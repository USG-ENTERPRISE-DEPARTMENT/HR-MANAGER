-- End of Service Benefit (EOSB). Idempotent.
--
-- EOSB = Annual Gross Salary × Years of Service × Days' Pay per Year ÷ 261 (the divisor is a setting).
-- Years run from the hire date to the effective date of the exit; a part year of 6 months or more
-- counts as a full year. The days per year come from the service band the employee falls into, and
-- that band's rate applies to every year. A settlement adds what the Bank still owes (leave, rent and
-- clothing allowance earned but not paid, the final month's salary) and deducts what the employee
-- owes (allowances paid in advance but not earned, notice pay, staff loans, Provident Fund), walks
-- the configured approval stages, and is posted to the GL when the last stage approves it.
--
-- Ids are generated by the application (as employeeleaves does) so the same statements run on MySQL.

-- Days' pay per year of service. A band covers service up to and including up_to_years; the last
-- band (up_to_years NULL) covers everything above the one before it.
CREATE TABLE IF NOT EXISTS eos_bands (
  id            BIGINT        PRIMARY KEY,
  up_to_years   INT,
  days_per_year NUMERIC(8,2)  NOT NULL,
  updated_by    BIGINT,
  updated_at    TIMESTAMP(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The Bank's starting rate table: 1–3 years 30 days, over 3–6 33, over 6–9 36, over 9–12 39, over 12 42.
INSERT INTO eos_bands (id, up_to_years, days_per_year)
SELECT v.id, v.up_to_years, v.days_per_year
FROM (VALUES (1, 3, 30), (2, 6, 33), (3, 9, 36), (4, 12, 39), (5, NULL::INT, 42))
     AS v(id, up_to_years, days_per_year)
WHERE NOT EXISTS (SELECT 1 FROM eos_bands);

-- Provident Fund: only the employees on this list have a fixed amount deducted from their EOSB.
CREATE TABLE IF NOT EXISTS eos_pf_list (
  id         BIGINT        PRIMARY KEY,
  employee   BIGINT        NOT NULL,
  amount     NUMERIC(14,2) NOT NULL,
  note       VARCHAR(255),
  updated_by BIGINT,
  updated_at TIMESTAMP(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT eos_pf_list_employee_key UNIQUE (employee)
);

-- One settlement per exit. The service, band, gross and benefit are worked out when it is saved and
-- kept on the row, so a later salary or band change never rewrites a settlement in approval or paid.
CREATE TABLE IF NOT EXISTS eos_settlements (
  id                BIGINT        PRIMARY KEY,
  settlement_number VARCHAR(20)   NOT NULL,
  employee          BIGINT        NOT NULL,
  exit_reason       VARCHAR(50)   NOT NULL,
  notified_date     DATE,
  effective_date    DATE          NOT NULL,
  hire_date         DATE,
  service_years     INT           NOT NULL DEFAULT 0,
  service_months    INT           NOT NULL DEFAULT 0,
  counted_years     INT           NOT NULL DEFAULT 0,
  days_per_year     NUMERIC(8,2)  NOT NULL DEFAULT 0,
  divisor           NUMERIC(8,2)  NOT NULL DEFAULT 261,
  annual_gross      NUMERIC(14,2) NOT NULL DEFAULT 0,
  gross_overridden  BOOLEAN       NOT NULL DEFAULT FALSE,
  eligible          BOOLEAN       NOT NULL DEFAULT TRUE,
  eosb_amount       NUMERIC(14,2) NOT NULL DEFAULT 0,
  total_additions   NUMERIC(14,2) NOT NULL DEFAULT 0,
  total_deductions  NUMERIC(14,2) NOT NULL DEFAULT 0,
  net_amount        NUMERIC(14,2) NOT NULL DEFAULT 0,
  notice_given      BOOLEAN       NOT NULL DEFAULT TRUE,
  salary_paid       BOOLEAN       NOT NULL DEFAULT FALSE,
  leave_paid        BOOLEAN       NOT NULL DEFAULT FALSE,
  rent_paid         BOOLEAN       NOT NULL DEFAULT TRUE,
  clothing_paid     BOOLEAN       NOT NULL DEFAULT FALSE,
  account_no        VARCHAR(50),
  branch            VARCHAR(100),
  next_of_kin       VARCHAR(150),
  notes             TEXT,
  status            VARCHAR(30)   NOT NULL DEFAULT 'Draft',
  created_by        BIGINT,
  submitted_at      TIMESTAMP(0),
  approved_by       BIGINT,
  approved_at       TIMESTAMP(0),
  rejection_reason  VARCHAR(500),
  document_ref      VARCHAR(100),
  payment_log       TEXT,
  posted_at         TIMESTAMP(0),
  exit_applied_at   TIMESTAMP(0),
  created_at        TIMESTAMP(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        TIMESTAMP(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT eos_settlements_number_key UNIQUE (settlement_number)
);

CREATE INDEX IF NOT EXISTS eos_settlements_employee_idx ON eos_settlements (employee);
CREATE INDEX IF NOT EXISTS eos_settlements_status_idx   ON eos_settlements (status);

-- Additions (the Bank pays the employee) and deductions (recovered from the employee). gl_account is
-- the other side of the employee's account: debited for an addition, credited for a deduction (for a
-- loan, the loan account).
CREATE TABLE IF NOT EXISTS eos_settlement_lines (
  id            BIGINT        PRIMARY KEY,
  settlement_id BIGINT        NOT NULL,
  line_type     VARCHAR(10)   NOT NULL,
  item_code     VARCHAR(30)   NOT NULL,
  description   VARCHAR(255)  NOT NULL,
  basis         VARCHAR(255),
  amount        NUMERIC(14,2) NOT NULL,
  gl_account    VARCHAR(50),
  sort_order    INT           NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS eos_settlement_lines_settlement_idx ON eos_settlement_lines (settlement_id);

-- The approval flow configured in Settings → Approvals, copied onto a settlement when it is submitted.
CREATE TABLE IF NOT EXISTS eos_settlement_stages (
  id             BIGINT       PRIMARY KEY,
  settlement_id  BIGINT       NOT NULL,
  stage_order    INT          NOT NULL,
  stage_name     VARCHAR(100) NOT NULL,
  approver_type  VARCHAR(10)  NOT NULL,
  approver_id    VARCHAR(50)  NOT NULL,
  approver_label VARCHAR(150),
  status         VARCHAR(20)  NOT NULL DEFAULT 'Pending',
  acted_by       BIGINT,
  acted_at       TIMESTAMP(0),
  comment        VARCHAR(500)
);

CREATE INDEX IF NOT EXISTS eos_settlement_stages_settlement_idx ON eos_settlement_stages (settlement_id);

-- Status history, one row per transition.
CREATE TABLE IF NOT EXISTS eos_log (
  id            BIGINT       PRIMARY KEY,
  settlement_id BIGINT       NOT NULL,
  user_id       BIGINT,
  action        VARCHAR(500) NOT NULL,
  status_from   VARCHAR(30),
  status_to     VARCHAR(30),
  created_at    TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS eos_log_settlement_idx ON eos_log (settlement_id);

